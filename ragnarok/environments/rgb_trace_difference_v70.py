"""Pixel differences of the agent's own paid, aligned counterfactual branches.

This supplies observations for a future controllability target, not identities,
object boxes or a ME decision. A truncated branch contributes no invented tail.
"""
from dataclasses import dataclass
import numpy as np
from ragnarok.environments.rgb_branch_trace_v70 import RGBBranchTrace


@dataclass(frozen=True)
class RGBTraceDifference:
    changed: np.ndarray
    first_changed_frame: np.ndarray
    unpaired_intervention_frames: int
    unpaired_control_frames: int


def _validate(trace):
    if not isinstance(trace, RGBBranchTrace):
        raise ValueError('Paid RGB branch trace required')
    raw, pooled, endpoint = trace.raw, trace.pooled, trace.endpoint
    if (not all(isinstance(x, np.ndarray) and x.dtype == np.uint8 for x in (raw, pooled, endpoint))
            or raw.ndim != 4 or raw.shape[-1] != 3 or raw.shape[0] > 64
            or any(d <= 0 for d in raw.shape[1:]) or pooled.shape != raw.shape
            or endpoint.shape != raw.shape[1:]
            or (len(raw) and not np.array_equal(pooled[-1], endpoint))):
        raise ValueError('Aligned uint8 RGB traces and exact pooled endpoint required')


def difference(intervention, control, *, image_kind='raw'):
    """Return only shared actual frame offsets; zero means no observed change.

Frame numbers are 1-based native frames after the shared anchor. The caller
must supply branches generated by one branch_pair_trace operation; pixels
alone cannot certify their provenance. Raw vs pooled is explicit because
pooling can retain a previous pixel and change the first visible divergence.
"""
    _validate(intervention)
    _validate(control)
    if image_kind not in ('raw', 'pooled'):
        raise ValueError('Choose raw or pooled images explicitly')
    left, right = getattr(intervention, image_kind), getattr(control, image_kind)
    if left.shape[1:] != right.shape[1:]:
        raise ValueError('Branches must share their RGB geometry')
    count = min(len(left), len(right))
    changed = np.any(left[:count] != right[:count], axis=-1)
    first = np.zeros(left.shape[1:3], dtype=np.uint8)
    if count:
        observed = changed.any(axis=0)
        first[observed] = (changed.argmax(axis=0)[observed]+1).astype(np.uint8)
    return RGBTraceDifference(changed, first, len(left)-count, len(right)-count)
